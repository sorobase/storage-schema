//! Emitters for the `contractstoragev0` Wasm custom section.
//!
//! ```ignore
//! use sik_storage_schema_macros::storage_schema;
//!
//! #[storage_schema]            // must sit ABOVE #[contracttype]
//! #[contracttype]
//! pub enum DataKey {
//!     #[storage(temporary, value = AllowanceValue)]
//!     Allowance(AllowanceDataKey),
//!     #[storage(persistent, value = i128)]
//!     Balance(Address),
//!     #[storage(instance, value = Address)]
//!     Admin,
//! }
//! ```
//!
//! The per-variant `#[storage(..)]` shape is the one sketched in
//! rs-soroban-sdk#1762, so a key enum annotated for this macro reads the same
//! as one annotated for that proposal. The macro adds no code: it strips its
//! helper attributes and emits `#[link_section]` byte statics only.
//!
//! - `#[storage_schema(lib = "..", default = persistent, types(A, B), embed_types = false)]`
//! - per variant: `#[storage(<instance|persistent|temporary>, value = T, doc = "..")]` or `#[storage(skip)]`
//! - `#[storage_key(instance, value = u32)] const COUNTER: Symbol = symbol_short!("COUNTER");`
//! - `storage_schema_extern! { #[storage_schema(lib = "crate@ver")] enum TheirKey { .. } }`
//!   declares keys written by a dependency that does not use this macro.
//!
//! UDT value and key-field types are embedded as `SC_STORAGE_ENTRY_TYPE_V0`
//! entries by calling the type's `spec_xdr()` const fn (generated by
//! `#[contracttype]` in soroban-sdk 25 and 28), because spec shaking removes
//! storage-only types from `contractspecv0`. Types nested inside those UDTs
//! are not followed: list them in `types(..)`.
//!
//! Building with `RUSTFLAGS="--cfg sik_storage_schema_off"` removes every
//! emitted static (used to measure the size cost against an identical build).

use proc_macro::TokenStream;
use proc_macro2::{Span, TokenStream as TokenStream2};
use quote::{format_ident, quote};
use sik_storage_schema_core::model::{encode_entry, Durability, KeyEntry, KeyField, KeyPattern, SchemaEntry};
use sik_storage_schema_core::rusttype::map_type;
use stellar_xdr::{ScSymbol, ScVal};
use syn::parse::{Parse, ParseStream, Parser};
use syn::punctuated::Punctuated;
use syn::{parse_macro_input, Attribute, Expr, Fields, ItemConst, ItemEnum, Lit, LitStr, Meta, Path, Token, Type};

struct EnumOpts {
    lib: String,
    default: Option<Durability>,
    types: Vec<Path>,
    embed_types: bool,
}

fn durability_of(p: &Path) -> Option<Durability> {
    let id = p.get_ident()?.to_string();
    Durability::parse(&id)
}

fn lit_str(e: &Expr) -> syn::Result<String> {
    match e {
        Expr::Lit(syn::ExprLit { lit: Lit::Str(s), .. }) => Ok(s.value()),
        other => Err(syn::Error::new_spanned(other, "expected a string literal")),
    }
}

fn lit_bool(e: &Expr) -> syn::Result<bool> {
    match e {
        Expr::Lit(syn::ExprLit { lit: Lit::Bool(b), .. }) => Ok(b.value),
        other => Err(syn::Error::new_spanned(other, "expected true or false")),
    }
}

fn parse_enum_opts(args: TokenStream2) -> syn::Result<EnumOpts> {
    let mut o = EnumOpts { lib: String::new(), default: None, types: vec![], embed_types: true };
    let metas = Punctuated::<Meta, Token![,]>::parse_terminated.parse2(args)?;
    for m in metas {
        match &m {
            Meta::NameValue(nv) if nv.path.is_ident("lib") => o.lib = lit_str(&nv.value)?,
            Meta::NameValue(nv) if nv.path.is_ident("embed_types") => o.embed_types = lit_bool(&nv.value)?,
            Meta::NameValue(nv) if nv.path.is_ident("default") => {
                let Expr::Path(p) = &nv.value else {
                    return Err(syn::Error::new_spanned(&nv.value, "expected instance, persistent or temporary"));
                };
                o.default = Some(
                    durability_of(&p.path).ok_or_else(|| syn::Error::new_spanned(&p.path, "expected instance, persistent or temporary"))?,
                );
            }
            Meta::List(l) if l.path.is_ident("types") => {
                o.types = Punctuated::<Path, Token![,]>::parse_terminated.parse2(l.tokens.clone())?.into_iter().collect();
            }
            other => return Err(syn::Error::new_spanned(other, "unknown storage_schema option (lib, default, types, embed_types)")),
        }
    }
    Ok(o)
}

struct VariantOpts {
    skip: bool,
    durability: Option<Durability>,
    value: Option<Type>,
    doc: Option<String>,
}

/// Parses `instance, value = T, doc = ".."` where `value` takes a type.
struct StorageArgs(VariantOpts);

impl Parse for StorageArgs {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let mut o = VariantOpts { skip: false, durability: None, value: None, doc: None };
        while !input.is_empty() {
            let ident: syn::Ident = input.parse()?;
            let name = ident.to_string();
            if input.peek(Token![=]) {
                input.parse::<Token![=]>()?;
                match name.as_str() {
                    "value" => o.value = Some(input.parse()?),
                    "doc" => o.doc = Some(input.parse::<LitStr>()?.value()),
                    _ => return Err(syn::Error::new(ident.span(), "unknown storage option (value, doc)")),
                }
            } else if name == "skip" {
                o.skip = true;
            } else if let Some(d) = Durability::parse(&name) {
                if o.durability.replace(d).is_some() {
                    return Err(syn::Error::new(ident.span(), "durability given twice"));
                }
            } else {
                return Err(syn::Error::new(ident.span(), "expected instance, persistent, temporary, skip, value = T or doc = \"..\""));
            }
            if !input.is_empty() {
                input.parse::<Token![,]>()?;
            }
        }
        Ok(StorageArgs(o))
    }
}

fn doc_of(attrs: &[Attribute]) -> String {
    let mut lines = vec![];
    for a in attrs {
        if a.path().is_ident("doc") {
            if let Meta::NameValue(nv) = &a.meta {
                if let Ok(s) = lit_str(&nv.value) {
                    lines.push(s.trim().to_string());
                }
            }
        }
    }
    let mut d = lines.join("\n");
    d.truncate(1024);
    d
}

/// Collected output: encoded key entries plus UDT paths to embed.
#[derive(Default)]
struct Emission {
    key_bytes: Vec<u8>,
    udts: Vec<Path>,
}

impl Emission {
    fn add_udts(&mut self, paths: Vec<Path>) {
        for p in paths {
            let s = quote!(#p).to_string();
            if !self.udts.iter().any(|q| quote!(#q).to_string() == s) {
                self.udts.push(p);
            }
        }
    }

    fn tokens(&self, ident_seed: &str, embed_types: bool) -> TokenStream2 {
        let len = self.key_bytes.len();
        let lit = proc_macro2::Literal::byte_string(&self.key_bytes);
        let keys_ident = format_ident!("__SIK_STORAGE_KEYS_{}", ident_seed);
        let mut items = vec![quote! {
            #[cfg(not(sik_storage_schema_off))]
            #[cfg_attr(target_family = "wasm", link_section = "contractstoragev0")]
            static #keys_ident: [u8; #len] = *#lit;
        }];
        if embed_types && !self.udts.is_empty() {
            items.push(quote! {
                #[repr(C)]
                struct __SikStoragePair<const A: usize, const B: usize>([u8; A], [u8; B]);
            });
            for (i, p) in self.udts.iter().enumerate() {
                let id = format_ident!("__SIK_STORAGE_TYPE_{}_{}", ident_seed, i);
                items.push(quote! {
                    #[cfg(not(sik_storage_schema_off))]
                    #[cfg_attr(target_family = "wasm", link_section = "contractstoragev0")]
                    static #id: __SikStoragePair<4, { <#p>::spec_xdr().len() }> =
                        __SikStoragePair([0u8, 0, 0, 1], <#p>::spec_xdr());
                });
            }
        }
        quote! {
            #[allow(unexpected_cfgs, non_upper_case_globals, dead_code)]
            const _: () = { #(#items)* };
        }
    }
}

fn push_key(em: &mut Emission, entry: KeyEntry, span: Span) -> syn::Result<()> {
    let bytes = encode_entry(&SchemaEntry::Key(entry)).map_err(|e| syn::Error::new(span, e.to_string()))?;
    em.key_bytes.extend(bytes);
    Ok(())
}

/// Shared by the attribute and the extern macro. Returns the enum with
/// helper attributes removed, and the emission.
fn process_enum(opts: &EnumOpts, mut item: ItemEnum) -> syn::Result<(ItemEnum, Emission)> {
    let mut em = Emission::default();
    let ename = item.ident.to_string();
    for v in item.variants.iter_mut() {
        let mut found: Option<VariantOpts> = None;
        let mut kept = vec![];
        for a in v.attrs.drain(..) {
            if a.path().is_ident("storage") {
                if found.is_some() {
                    return Err(syn::Error::new_spanned(&a, "duplicate #[storage]"));
                }
                found = Some(a.parse_args::<StorageArgs>()?.0);
            } else {
                kept.push(a);
            }
        }
        v.attrs = kept;
        let vname = v.ident.to_string();
        let Some(o) = found else {
            return Err(syn::Error::new_spanned(
                &v.ident,
                format!("variant {ename}::{vname} needs #[storage(<instance|persistent|temporary>, value = T)] or #[storage(skip)]"),
            ));
        };
        if o.skip {
            continue;
        }
        let durability = o.durability.or(opts.default).ok_or_else(|| {
            syn::Error::new_spanned(&v.ident, "missing durability (instance, persistent, temporary) and no default = .. on the enum")
        })?;
        let value_ty = o.value.ok_or_else(|| syn::Error::new_spanned(&v.ident, "missing value = T"))?;
        let mut udts = vec![];
        let value = map_type(&value_ty, &mut udts).map_err(|e| syn::Error::new_spanned(&value_ty, e.0))?;
        if v.discriminant.is_some() {
            return Err(syn::Error::new_spanned(
                &v.ident,
                "integer-discriminant key enums encode as U32; declare those keys with a sidecar exact pattern",
            ));
        }
        let fields = match &v.fields {
            Fields::Unit => vec![],
            Fields::Unnamed(u) => {
                let mut out = vec![];
                for f in &u.unnamed {
                    out.push(KeyField {
                        name: String::new(),
                        type_: map_type(&f.ty, &mut udts).map_err(|e| syn::Error::new_spanned(&f.ty, e.0))?,
                    });
                }
                out
            }
            Fields::Named(n) => return Err(syn::Error::new_spanned(n, "named-field variants are not supported by #[contracttype]")),
        };
        em.add_udts(udts);
        let doc = o.doc.unwrap_or_else(|| doc_of(&v.attrs));
        push_key(
            &mut em,
            KeyEntry {
                doc,
                lib: opts.lib.clone(),
                name: format!("{ename}::{vname}"),
                durability,
                key: KeyPattern::Tagged { tag: vname, fields },
                value,
            },
            v.ident.span(),
        )?;
    }
    em.add_udts(opts.types.clone());
    Ok((item, em))
}

/// Attribute for a `#[contracttype]` storage-key enum. Place it above
/// `#[contracttype]` so it runs first and strips its `#[storage]` helpers.
#[proc_macro_attribute]
pub fn storage_schema(args: TokenStream, input: TokenStream) -> TokenStream {
    let opts = match parse_enum_opts(args.into()) {
        Ok(o) => o,
        Err(e) => return e.to_compile_error().into(),
    };
    let item = parse_macro_input!(input as ItemEnum);
    let seed = item.ident.to_string();
    match process_enum(&opts, item) {
        Ok((item, em)) => {
            let statics = em.tokens(&seed, opts.embed_types);
            quote!(#item #statics).into()
        }
        Err(e) => e.to_compile_error().into(),
    }
}

/// Declare keys written by a dependency (or any enum you do not own). Emits
/// only the section bytes; the enum itself is not emitted.
///
/// ```ignore
/// storage_schema_extern! {
///     #[storage_schema(lib = "soroban-token-sdk@28.0.0", embed_types = false)]
///     enum TokenSdkKeys {
///         #[storage(instance, value = TokenMetadata)] METADATA,
///     }
/// }
/// ```
#[proc_macro]
pub fn storage_schema_extern(input: TokenStream) -> TokenStream {
    let mut item = parse_macro_input!(input as ItemEnum);
    let mut opts = EnumOpts { lib: String::new(), default: None, types: vec![], embed_types: true };
    let mut kept = vec![];
    for a in item.attrs.drain(..) {
        if a.path().is_ident("storage_schema") {
            let toks = match &a.meta {
                Meta::List(l) => l.tokens.clone(),
                _ => TokenStream2::new(),
            };
            match parse_enum_opts(toks) {
                Ok(o) => opts = o,
                Err(e) => return e.to_compile_error().into(),
            }
        } else {
            kept.push(a);
        }
    }
    item.attrs = kept;
    let seed = format!("EXTERN_{}", item.ident);
    match process_enum(&opts, item) {
        Ok((_item, em)) => em.tokens(&seed, opts.embed_types).into(),
        Err(e) => e.to_compile_error().into(),
    }
}

/// Attribute for a raw-key constant:
/// `#[storage_key(instance, value = u32)] const COUNTER: Symbol = symbol_short!("COUNTER");`
/// The symbol is read from a `symbol_short!("..")` initialiser, or given as
/// `symbol = ".."`. Options: `name = ".."`, `lib = ".."`, `doc = ".."`.
#[proc_macro_attribute]
pub fn storage_key(args: TokenStream, input: TokenStream) -> TokenStream {
    let item = parse_macro_input!(input as ItemConst);
    match storage_key_impl(args.into(), &item) {
        Ok(ts) => quote!(#item #ts).into(),
        Err(e) => e.to_compile_error().into(),
    }
}

struct KeyArgs {
    durability: Option<Durability>,
    value: Option<Type>,
    symbol: Option<String>,
    name: Option<String>,
    lib: String,
    doc: Option<String>,
}

impl Parse for KeyArgs {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let mut o = KeyArgs { durability: None, value: None, symbol: None, name: None, lib: String::new(), doc: None };
        while !input.is_empty() {
            let ident: syn::Ident = input.parse()?;
            let n = ident.to_string();
            if input.peek(Token![=]) {
                input.parse::<Token![=]>()?;
                match n.as_str() {
                    "value" => o.value = Some(input.parse()?),
                    "symbol" => o.symbol = Some(input.parse::<LitStr>()?.value()),
                    "name" => o.name = Some(input.parse::<LitStr>()?.value()),
                    "lib" => o.lib = input.parse::<LitStr>()?.value(),
                    "doc" => o.doc = Some(input.parse::<LitStr>()?.value()),
                    _ => return Err(syn::Error::new(ident.span(), "unknown option (value, symbol, name, lib, doc)")),
                }
            } else if let Some(d) = Durability::parse(&n) {
                o.durability = Some(d);
            } else {
                return Err(syn::Error::new(ident.span(), "expected a durability or option"));
            }
            if !input.is_empty() {
                input.parse::<Token![,]>()?;
            }
        }
        Ok(o)
    }
}

fn storage_key_impl(args: TokenStream2, item: &ItemConst) -> syn::Result<TokenStream2> {
    let a: KeyArgs = syn::parse2(args)?;
    let durability = a.durability.ok_or_else(|| syn::Error::new_spanned(&item.ident, "missing durability"))?;
    let value_ty = a.value.ok_or_else(|| syn::Error::new_spanned(&item.ident, "missing value = T"))?;
    let symbol = match a.symbol {
        Some(s) => s,
        None => match &*item.expr {
            Expr::Macro(m) if m.mac.path.segments.last().map(|s| s.ident == "symbol_short").unwrap_or(false) => {
                m.mac.parse_body::<LitStr>()?.value()
            }
            other => return Err(syn::Error::new_spanned(other, "cannot read the symbol from this initialiser; add symbol = \"..\"")),
        },
    };
    let mut em = Emission::default();
    let mut udts = vec![];
    let value = map_type(&value_ty, &mut udts).map_err(|e| syn::Error::new_spanned(&value_ty, e.0))?;
    em.add_udts(udts);
    let sym = ScSymbol(symbol.as_str().try_into().map_err(|_| syn::Error::new_spanned(&item.ident, "symbol longer than 32 bytes"))?);
    push_key(
        &mut em,
        KeyEntry {
            doc: a.doc.unwrap_or_else(|| doc_of(&item.attrs)),
            lib: a.lib,
            name: a.name.unwrap_or_else(|| item.ident.to_string()),
            durability,
            key: KeyPattern::Exact(ScVal::Symbol(sym)),
            value,
        },
        item.ident.span(),
    )?;
    Ok(em.tokens(&format!("CONST_{}", item.ident), true))
}
